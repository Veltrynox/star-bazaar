#!/usr/bin/env python3
"""Writes planes.json and planes.js for the sun debug page.
Reads the constants from game/fx/sun/sun_flare.gd (regex, with line numbers) and repeats the per-plane
formulas of _ready() and _layout() there. If those formulas change in the GDScript, update here.
Run: python3 tools/sun_debug/make_planes.py"""
import json, math, re, os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
GD = "game/fx/sun/sun_flare.gd"
lines = open(os.path.join(ROOT, GD)).read().split("\n")

def const(name, cast):
    for n, l in enumerate(lines, 1):
        m = re.match(r"\s*(?:const|var)\s+%s\s*:?=\s*(\"[^\"]*\"|[-0-9.]+)" % name, l)
        if m:
            v = m.group(1)
            return cast(v.strip('"')), n
    raise SystemExit("constant not found: " + name)

PLANES, l_planes = const("PLANES", int)
GLOW, l_glow = const("PLANE_GLOW", float)
FPS, l_fps = const("FPS", float)
FRAMES, l_fc = const("FRAME_COUNT", int)
SPAN, l_span = const("PLANE_SPAN", float)
RADIUS, l_rad = const("radius", float)
GOLD, l_gold = const("golden", float)
# SETS and PLANE_SETS: lists of names / ints in the GDScript (one line each)
def lst(name):
    for n, l in enumerate(lines, 1):
        m = re.match(r"\s*const\s+%s\s*:?=\s*\[([^\]]*)\]" % name, l)
        if m: return [x.strip().strip('"') for x in m.group(1).split(",")], n
    raise SystemExit("list not found: " + name)
SETS, l_sets = lst("SETS")
PLANE_SETS, l_ps = [None, None]
_ps, l_ps = lst("PLANE_SETS"); PLANE_SETS = [int(x) for x in _ps]
SOURCE = SETS[0]
FRAME_PATH = re.search(r'FRAME_PATH := "res://([^"]*)"', "\n".join(lines)).group(1)

def fpm(x, m):  # GDScript fposmod
    return x - m * math.floor(x / m)

def deg(r): return math.degrees(r)
planes = []
for i in range(PLANES):
    y = 1.0 - 2.0 * (i + 0.5) / PLANES
    ring = math.sqrt(1.0 - y * y)
    az = math.tau * GOLD * i
    d = (math.cos(az) * ring, y, math.sin(az) * ring)  # plane normal direction (line 35-38)
    planes.append({
        "index": i,
        "dir": d,
        "yaw_deg": deg(math.atan2(d[0], d[2])),   # derived for display: angle around Y
        "pitch_deg": deg(math.asin(y)),           # derived for display: elevation
        "azimuth_deg": deg(az) % 360.0,           # az in the GDScript
        "set": SETS[PLANE_SETS[i]], "layer_base": PLANE_SETS[i] * FRAMES,                       # PLANE_SETS, layer_base in _ready()
        "phase": fpm(i * float(FRAMES) * GOLD, float(FRAMES)),                                  # _phase()
        "uv_center": [0.5 + (fpm(i * GOLD, 1.0) - 0.5) * 0.04,
                      0.5 + (fpm(i * GOLD * GOLD + 0.3, 1.0) - 0.5) * 0.04],                    # line 50
        "uv_scale": 0.9 + fpm(i * 0.37, 1.0) * 0.1,                                            # line 51
        "uv_rot": math.tau * fpm(i * GOLD * 2.0, 1.0),                                          # line 52
        "offset_z_radii": -(0.05 + 0.06 * (i % 3)),                                             # line 69
        "offset_z": -RADIUS * (0.05 + 0.06 * (i % 3)),
        "spin_rad_s": (0.04 + 0.03 * (i % 4)) * (1.0 if i % 2 == 0 else -1.0),                  # line 56
        "glow": GLOW,
    })

data = {
    "source_file": GD,
    "lines": {"PLANES": l_planes, "PLANE_GLOW": l_glow, "FPS": l_fps, "SETS": l_sets, "PLANE_SETS": l_ps, "FRAME_COUNT": l_fc,
              "PLANE_SPAN": l_span, "radius": l_rad, "golden": l_gold,
              "per_plane_formulas": "33-56 (_ready), 69 (_layout)", "shader": "game/fx/sun/sun.gdshader 16-30"},
    "planes_count": PLANES, "plane_glow": GLOW, "fps": FPS, "sets": SETS, "frame_count": FRAMES,
    "plane_span": SPAN, "radius": RADIUS,
    "frame_url": "../../" + FRAME_PATH.replace("%s", SOURCE[len("sun_"):]).replace("%02d", "{NN}"),
    "planes": planes,
}
out = os.path.dirname(__file__)
js = json.dumps(data, indent=1)
open(os.path.join(out, "planes.json"), "w").write(js + "\n")
# planes.js: same data as a script, because fetch() of a .json does not work from file://
open(os.path.join(out, "planes.js"), "w").write("// generated by make_planes.py, do not edit\nconst SUN_DATA = " + js + ";\n")
print("planes:", PLANES, "glow:", GLOW, "fps:", FPS, "plane sets:", [pl["set"] for pl in planes], "phases:", [round(pl["phase"], 2) for pl in planes])

# frames.js: all three sets as base64 data URIs (no local image loads, browsers block them on file://)
# SUN_SETS = {name: [64 data URIs]}; SUN_DEFAULT is the first sheet (only a fallback name).
import base64
sets = {}
for name in SETS:
    uris = []
    for i in range(FRAMES):
        p = os.path.join(ROOT, FRAME_PATH.replace("%s", name[len("sun_"):]).replace("%02d", "%02d" % i))
        uris.append("data:image/png;base64," + base64.b64encode(open(p, "rb").read()).decode())
    sets[name] = uris
body = ",\n".join('"%s": [\n%s\n]' % (n, ",\n".join(' "%s"' % u for u in us)) for n, us in sets.items())
open(os.path.join(out, "frames.js"), "w").write("// generated by make_planes.py, do not edit\nconst SUN_DEFAULT = \"%s\";\nconst SUN_SETS = {\n%s\n};\n" % (SOURCE, body))
print("frames.js:", {n: len(u) for n, u in sets.items()}, "default", SOURCE)
