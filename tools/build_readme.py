#!/usr/bin/env python3
"""Build README.md. README.md is GENERATED: never edit it by hand.

  python3 tools/build_readme.py           write README.md
  python3 tools/build_readme.py --check   exit 1 if README.md is out of date (no write)

Sources: tools/readme_intro.md (hand-written intro), tools/project_workflow.html (the workflow
diagram data and notes become a Mermaid diagram and a list), .claude/agents/*.md (agent table).
The Claude Code hook in tools/gdd_sync.py runs this on `git push` and commits README.md if it changed.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "README.md"
KIND_STYLE = {
    "rule": "fill:#fdecc8,stroke:#b8860b,color:#222", "person": "fill:#dbeafe,stroke:#2563eb,color:#222",
    "agent": "fill:#dcfce7,stroke:#16a34a,color:#222", "file": "fill:#f3f4f6,stroke:#6b7280,color:#222",
    "gen": "fill:#fce7f3,stroke:#be185d,color:#222",
}
NODE = re.compile(r"^  (\w+):\s+\['(\w+)',\s*\d+,\s*\d+,\s*\d+,\s*\d+,\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'\]", re.M)
EDGE = re.compile(r"^  \['(\w+)','\w','(\w+)','\w','((?:[^'\\]|\\.)*)'(, true)?", re.M)


def q(s):
    return s.replace("\\'", "'").replace('"', "'").replace("<", "&lt;").replace(">", "&gt;")


def workflow():
    html = (ROOT / "tools" / "project_workflow.html").read_text()
    nodes = {m[1]: (m[2], q(m[3]), q(m[4])) for m in NODE.finditer(html)}
    edges = [(m[1], m[2], q(m[3]), bool(m[4])) for m in EDGE.finditer(html)]
    out = ["```mermaid", "flowchart LR"]
    agents = [i for i, n in nodes.items() if n[0] == "agent"]
    for i, (kind, title, sub) in nodes.items():
        if i in agents or kind == "group":
            continue
        out.append('  %s["<b>%s</b><br/>%s"]:::%s' % (i, title, sub, kind))
    out.append('  subgraph roles["Role agents (star = owner starts by hand only)"]')
    for i in agents:
        out.append('    %s["<b>%s</b><br/>%s"]:::agent' % (i, nodes[i][1], nodes[i][2]))
    out.append("  end")
    for f, t, label, dashed in edges:
        f = "roles" if f == "group" else f
        t = "roles" if t == "group" else t
        arrow = "-.->" if dashed else "-->"
        out.append("  %s %s%s %s" % (f, arrow, ('|"%s"|' % label) if label else "", t))
    for kind, style in KIND_STYLE.items():
        out.append("  classDef %s %s" % (kind, style))
    out.append("```")
    notes = re.search(r'<div class="notes">(.*?)\n  </div>\s*</main>', html, re.S).group(1)
    items = []
    for d in re.findall(r"<div>(.*?)</div>", notes, re.S):
        t = re.sub(r"<b>(.*?)</b>", r"**\1**", d)
        t = re.sub(r"<code>(.*?)</code>", r"`\1`", t)
        t = re.sub(r"<[^>]+>", "", t).strip()
        if t:
            items.append("- " + t)
    return "\n".join(out), "\n".join(items)


def agent_table():
    rows = ["| Agent | Use for |", "|---|---|"]
    for p in sorted((ROOT / ".claude" / "agents").glob("*.md")):
        txt = p.read_text()
        name = re.search(r"^name:\s*(.+)$", txt, re.M)
        desc = re.search(r"^description:\s*(.+)$", txt, re.M)
        if name and desc:
            d = desc.group(1).strip().replace("|", "/")
            d = re.split(r"\. Do not use|\. Not for", d)[0]
            rows.append("| %s | %s |" % (name.group(1).strip(), d[:230] + ("..." if len(d) > 230 else "")))
    return "\n".join(rows)


def build():
    diagram, notes = workflow()
    intro = (ROOT / "tools" / "readme_intro.md").read_text().rstrip("\n")
    return "\n\n".join([
        "<!-- GENERATED by tools/build_readme.py from tools/readme_intro.md, tools/project_workflow.html and "
        ".claude/agents/*.md. Do not edit by hand: change the source and run `python3 tools/build_readme.py`. -->",
        intro,
        "## How the work flows\n\nAgents keep no memory between sessions, so everything passes through files. "
        "Interactive version: [tools/project_workflow.html](tools/project_workflow.html) (open it in a browser).\n\n" + diagram,
        "## Rules and commit checks\n\n" + notes,
        "## Agents\n\n" + agent_table(),
    ]) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("ok" if ok else "README.md is out of date: run python3 tools/build_readme.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print("wrote README.md")
