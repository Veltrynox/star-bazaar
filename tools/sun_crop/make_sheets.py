#!/usr/bin/env python3
"""Embeds the three sun sheets as base64 data URIs in tools/sun_crop/sheets.js.
Browsers block local image files for a page opened from disk, so the page reads this file instead.
Run from anywhere:  python3 tools/sun_crop/make_sheets.py
The PNGs in art/ are only read."""
import base64, os, struct

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHEETS = {"v01": "art_source/sun_sheet_storm_8x8_v01.png", "v02": "art_source/sun_sheet_flare_8x8_v02.png", "v03": "art_source/sun_sheet_calm_8x8_v03.png"}
out = os.path.join(ROOT, "tools/sun_crop/sheets.js")

lines = ["// Generated by make_sheets.py. Do not edit.", "const SUN_SHEETS = {"]
for key, rel in SHEETS.items():
    data = open(os.path.join(ROOT, rel), "rb").read()
    w, h = struct.unpack(">II", data[16:24])  # IHDR width and height
    print("%s: %s %dx%d, %d bytes" % (key, rel, w, h, len(data)))
    lines.append('  "%s": {"name": "%s", "w": %d, "h": %d, "uri": "data:image/png;base64,%s"},'
                 % (key, os.path.basename(rel), w, h, base64.b64encode(data).decode()))
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print("wrote %s (%.2f MB)" % (out, os.path.getsize(out) / 1e6))
